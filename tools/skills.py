#!/usr/bin/env python3
"""Keep Master-Repo's skills usable by every agent.

`skills/<name>.md` holds the shipped skills. `local/skills/<name>.md` overrides one by name, adds a new one, or
hides one with `disabled: true` in its frontmatter; nothing in skills/ is edited, so updates to it never conflict.
This tool merges the two and generates:

- `skills/INDEX.md`: the short list every agent reads at session start (AGENTS.md points here;
  Codex and any other agent use it to decide which skill to load).
- `.claude/skills/<name>/SKILL.md`: thin wrappers so Claude Code loads the right skill on its own.

Usage (from the Master-Repo root):
    python3 tools/skills.py sync     # regenerate both after adding or editing a skill
    python3 tools/skills.py check    # fail if a skill is malformed or the generated files are stale
    python3 tools/skills.py override <name>   # copy skills/<name>.md to local/skills/ to edit it there
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths  # noqa: E402

ROOT = paths.ROOT  # the data directory (MASTER_REPO_ROOT, or this checkout)
MARKER = "<!-- generated by tools/skills.py; edit skills/<name>.md instead -->"
LOCAL = Path("local") / "skills"
REQUIRED = ("name", "title", "kind", "when", "status")
KINDS = {  # kind → INDEX.md heading, in order
    "session": "Sessions (a whole conversation with a scope)",
    "task": "Tasks (a focused job, often inside a session)",
    "project": "In a project repo (for agents coding in one of the owner's project repos)",
}


def parse(path: Path) -> dict:
    """Frontmatter of simple `key: value` lines; values may be JSON strings or [a, b] lists."""
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    if not m:
        raise ValueError(f"{path.name}: missing frontmatter")
    meta: dict = {}
    for line in m.group(1).splitlines():
        if not line.strip() or ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith("[") and value.endswith("]"):
            value = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        meta[key.strip()] = value
    meta["body"] = m.group(2).strip()
    if meta.get("disabled") == "true":
        return meta  # a stub that only hides the shipped skill of the same name
    missing = [k for k in REQUIRED if not meta.get(k)]
    if missing:
        raise ValueError(f"{path.name}: missing {', '.join(missing)}")
    if meta["name"] != path.stem:
        raise ValueError(f"{path.name}: name '{meta['name']}' must match the file name")
    if meta["kind"] not in KINDS:
        raise ValueError(f"{path.name}: kind must be one of {', '.join(KINDS)}")
    return meta


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def skill_files(folder: Path) -> list[Path]:
    return sorted(p for p in folder.glob("*.md") if p.name not in ("INDEX.md", "README.md"))


def load(root: Path = ROOT) -> list[dict]:
    """Shipped skills merged with local/skills/: a local file wins by name, and a disabled one hides it."""
    merged = {}
    for p in skill_files(root / "skills"):
        merged[p.stem] = {**parse(p), "path": f"skills/{p.name}"}
    for p in skill_files(root / LOCAL):
        meta = parse(p)
        if meta.get("disabled") == "true":
            merged.pop(p.stem, None)
        else:
            merged[p.stem] = {**meta, "path": f"{LOCAL.as_posix()}/{p.name}"}
    return [merged[k] for k in sorted(merged)]


def drifted(root: Path = ROOT) -> list[str]:
    """Local overrides whose shipped skill changed since they were copied (their `based_on` no longer matches)."""
    out = []
    for p in skill_files(root / LOCAL):
        base = root / "skills" / p.name
        based_on = parse(p).get("based_on")
        if based_on and base.exists() and digest(base) != based_on:
            out.append(f"{LOCAL.as_posix()}/{p.name}: skills/{p.name} changed since you copied it; compare and set "
                       f"based_on: {digest(base)} when done")
    return out


def override(name: str, root: Path = ROOT) -> Path:
    """Copy a shipped skill into local/skills/, stamped with the version it came from."""
    base = root / "skills" / f"{name}.md"
    dest = root / LOCAL / f"{name}.md"
    if not base.exists():
        raise ValueError(f"no skill skills/{name}.md")
    if dest.exists():
        raise ValueError(f"{dest.relative_to(root)} already exists")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(base.read_text().replace("\n---\n", f"\nbased_on: {digest(base)}\n---\n", 1))
    return dest


def index_text(skills: list[dict]) -> str:
    lines = [
        "# Skills",
        "",
        MARKER,
        "",
        "Read this at the start of every session. When what the owner says matches a skill's \"use when\", read that skill's file and follow it. "
        "Several can apply in one session (a concern session may call investigate-repo and visualize). "
        "Fill parameters from what the owner said; ask only if one is missing. Don't make them name or copy a skill.",
        "",
        "If a session shows a repeatable way of working that no skill covers, write one: see [write-skill](write-skill.md).",
        "",
    ]
    if any(s["path"].startswith(LOCAL.as_posix()) for s in skills):
        lines += [
            "Some skills below are local copies (in `local/skills/`). Wherever any file mentions `skills/<name>.md`, "
            "read the copy this list links to instead.",
            "",
        ]
    for kind, heading in KINDS.items():
        if kind == "project" and not any(s["kind"] == kind for s in skills):
            continue
        lines += [f"## {heading}", "", "| Skill | Use when | Parameters |", "| --- | --- | --- |"]
        for s in skills:
            if s["kind"] != kind:
                continue
            status = "" if s["status"] == "ready" else f" *({s['status']})*"
            params = ", ".join(s.get("params") or []) or "none"
            link = s["path"].removeprefix("skills/") if s["path"].startswith("skills/") else f"../{s['path']}"
            lines.append(f"| [{s['name']}]({link}){status} | {s['when']} | {params} |")
        lines.append("")
    return "\n".join(lines)


def wrapper_text(s: dict) -> str:
    params = ", ".join(s.get("params") or [])
    return "\n".join([
        "---",
        f"name: {s['name']}",
        f"description: {json.dumps(s['when'] + ' (Master-Repo skill: ' + s['title'] + ')')}",
        "---",
        "",
        MARKER,
        "",
        f"Follow `{s['path']}` in the Master-Repo root. If you haven't read `AGENTS.md` this session, read it first.",
        (f"Fill the parameters ({params}) from what the owner said; ask only if one is missing." if params else ""),
        "",
    ])


def expected(root: Path = ROOT) -> dict[Path, str]:
    skills = load(root)
    files = {root / "skills" / "INDEX.md": index_text(skills) + "\n"}
    for s in skills:
        if s["status"] == "ready":
            files[root / ".claude" / "skills" / s["name"] / "SKILL.md"] = wrapper_text(s)
    return files


def stale_wrappers(root: Path, keep: set[Path]) -> list[Path]:
    base = root / ".claude" / "skills"
    if not base.exists():
        return []
    return [p.parent for p in base.glob("*/SKILL.md") if p not in keep and MARKER in p.read_text()]


def sync(root: Path = ROOT) -> None:
    files = expected(root)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"wrote {path.relative_to(root)}")
    for d in stale_wrappers(root, set(files)):
        shutil.rmtree(d)  # only generated wrappers carry the marker
        print(f"removed {d.relative_to(root)}")
    for line in drifted(root):
        print(f"note: {line}")


def check(root: Path = ROOT) -> int:
    try:
        files = expected(root)
    except ValueError as e:
        print(e)
        return 1
    bad = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
    bad += stale_wrappers(root, set(files))
    for p in bad:
        print(f"stale: {p.relative_to(root)} (run python3 tools/skills.py sync)")
    for line in drifted(root):
        print(f"note: {line}")  # a nudge, not a failure: the local copy still works
    return 1 if bad else 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "sync"
    if cmd == "sync":
        sync()
    elif cmd == "check":
        sys.exit(check())
    elif cmd == "override" and len(sys.argv) == 3:
        try:
            print(f"wrote {override(sys.argv[2]).relative_to(ROOT)}; edit it there, then run sync")
        except ValueError as e:
            sys.exit(str(e))
    else:
        sys.exit(__doc__)
